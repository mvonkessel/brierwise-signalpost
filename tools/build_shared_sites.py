"""Write src/brierwise_signalpost/shared_sites.py from the public company universe.

python tools/build_shared_sites.py signalpost-company-universe-2025.jsonl.gz

A website that three or more legal entities list in the register is a manager's, a chain's or a group's site, not the
own site of any one of them. The universe is Builderr's public file; only domains and their count are used.
"""
import collections
import gzip
import json
import os
import sys
from urllib.parse import urlsplit

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from brierwise_signalpost.website import NOT_OWN, normalize_site, site_key  # noqa: E402

MINIMUM = 3


def main(path: str) -> None:
    count = collections.Counter()
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        for line in fh:
            site = normalize_site((json.loads(line).get("website") or "").strip())
            host = site_key(urlsplit(site).hostname) if site else ""
            if host and not NOT_OWN.search(host):
                count[host] += 1
    shared = sorted(h for h, n in count.items() if n >= MINIMUM)
    out = os.path.join(ROOT, "src", "brierwise_signalpost", "shared_sites.py")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""Websites that %d or more legal entities list in the register (public universe, 2025 snapshot).\n\n'
                 'Generated by tools/build_shared_sites.py; see the docstring there.\n"""\n\nSHARED_SITES = frozenset("""\n'
                 % MINIMUM)
        line = ""
        for host in shared:
            if len(line) + len(host) + 1 > 118:
                fh.write(line.rstrip() + "\n")
                line = ""
            line += host + " "
        fh.write(line.rstrip() + '\n""".split())\n')
    print(len(count), "domains,", len(shared), "shared by at least", MINIMUM)


if __name__ == "__main__":
    main(sys.argv[1])
